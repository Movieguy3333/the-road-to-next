const seed = async () => {
  // Note: this is a safeguard to ensure that the database is empty before seeding

  // Note: The .ticket property is automatically generated by Prisma based on the schema.prisma file in your project. Prisma creates a lowercase (camelCase) property on the client instance so you can interact with that specific database table. Because the model is named Ticket (capital T), the Prisma Client exposes prisma.ticket (lowercase t). This property contains all the built-in database methods (deleteMany, createMany, findUnique, etc.) specifically mapped to that table.

  /* Note: Very interesting. you must delete the tickets before deleting the users. If you delete the user first, the ticket schema would be violated, since every ticket has to have a user.
However, since we added the following to the ticket schema:
user User @relation(fields: [userId], references: [id], onDelete: Cascade)

We can swap the delete order and it will work. so the follwing will work:
  await prisma.user.deleteMany();
 await prisma.ticket.deleteMany();


however, we will just leave it as it is.
  */
  await prisma.ticket.deleteMany();
  await prisma.user.deleteMany();

  // Note: two ways to seed data
  /*  for (const ticket of tickets) {
    await prisma.ticket.create({
      data: ticket,
    });
  } */
  /* 
    const promises = tickets.map(async (ticket) => {
      await prisma.ticket.create({
        data: ticket,
      });

      await Promise.all(promises);
    ; */

  const passwordHash = await hash("password");

  const dbUsers = await prisma.user.createManyAndReturn({
    data: users.map((user) => ({
      ...user,
      passwordHash,
    })),
  });

  await prisma.ticket.createMany({
    data: tickets.map((ticket) => ({
      ...ticket,
      userId: dbUsers[0].id,
    })),
  });
};

seed();
